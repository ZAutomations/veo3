const assert=require('assert'),fs=require('fs'),os=require('os'),path=require('path'),cp=require('child_process');
const F=require('../fern_topic_visuals'),W=require('../write_story'),S=require('../single_scene_prompts');
const p=W.loadPreset('fern-documentary');
assert(!p.style.includes('3D aircraft'));
assert(p.direction.includes(F.CONTRACT));
const look=W.lookBlock(p,'An anatomy display');
assert(!look.includes('the entire film happens in this one place'));
const castPrompt=W.castPrompt(p,[]);
assert(castPrompt.includes('TOPIC-SPECIFIC reference setting'));
assert(!castPrompt.includes('Choose ONE place for this whole film'));
const sceneInstructions=W.scenesPrompt(p,[],[{title:'Discovery',beat:'An owner discovers a missing painting in the gallery.'}],0,1,[],'Gallery reference');
assert(!sceneInstructions.includes('THE PLACE IS FIXED'));
assert(sceneInstructions.includes('Stay in one setting when appropriate'));
assert(sceneInstructions.includes('name the location in each shot'));
assert(p.direction.includes('Use one location when all narrated actions belong there'));
assert(p.direction.includes('Do not invent a getaway'));
const narration='Inside the chest, the diaphragm contracts and draws air into the lungs.';
const visual='SHOT 1 (0-3s): Faceless mannequin chest expands. SHOT 2 (3-5s): Non-graphic 3D diaphragm contracts. SHOT 3 (5-8s): Air arrows enter the lungs.';
const story=W.buildStory(p,[],{description:'How breathing works',place_name:'Anatomy',place_description:'A neutral anatomy presentation setting',place_prompt:'Empty slate 3D presentation setting'},[{scene_title:'Breathing',script_line:narration,narrative_context:visual,characters:[]}]);
story.title='How breathing works';
assert(story.scenes[0].narrative_context.includes(F.CONTRACT));
assert.equal(story.scenes[0].script_line,narration);
const single=S.promptForScene(story,0);
assert(single.includes('FILM TOPIC: How breathing works'));
assert(single.includes('specific organ or process'));
assert(single.includes(visual));assert(single.includes(narration));
assert(single.includes('REFERENCE SETTING (matching shots only)'));
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'fern-topic-'));
try{W.writePackage(dir,p,story,[]);assert(!fs.readFileSync(path.join(dir,'character_sheets.txt'),'utf8').includes('This is the ONE place this film happens in'));assert(fs.readFileSync(path.join(dir,'style_bible.md'),'utf8').includes('Each event uses its actual location and time'));const file=path.join(dir,'story.json');fs.writeFileSync(file,JSON.stringify(story));const result=cp.spawnSync(process.execPath,[path.resolve(__dirname,'../story_to_agent_prompt.js'),file,'--print'],{encoding:'utf8'});assert.equal(result.status,0,result.stderr);assert(result.stdout.includes(F.CONTRACT));assert(result.stdout.includes(narration));assert(result.stdout.includes(visual));}finally{fs.rmSync(dir,{recursive:true,force:true});}
const unrelated={title:'Other story',style:'Other style',scenes:[{script_line:'Unchanged words',narrative_context:'A garden'}]};
assert(!S.promptForScene(unrelated,0).includes(F.CONTRACT));
console.log('PASS: Fern topic, anatomy, mannequin identity and narration survive writing and both exports; location is a matching design reference; unrelated presets unaffected.');
